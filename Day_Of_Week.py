print("Pick a day of the week (1-7):")
input_day = int(input())

if input_day == 1:
    print("Monday")
elif input_day == 2:
    print("Tuesday")
elif input_day == 3:
    print("Wednesday")
elif input_day == 4:
    print("Thursday")
elif input_day == 5:
    print("Friday")
elif input_day == 6:
    print("Saturday")
elif input_day == 7:
    print("Sunday")
else:
    print("That is not a prompted number, please do it again.")